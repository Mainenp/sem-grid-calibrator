const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const source=fs.readFileSync(require('node:path').join(__dirname,'public/app.js'),'utf8');
const drawSource=source.slice(source.indexOf('function draw() {'),source.indexOf('function resetSingleAnalysis()'));
let assignments=0,width=8192,height=8686;
const canvas={get width(){return width;},set width(v){assignments++;width=v;},get height(){return height;},set height(v){assignments++;height=v;}};
let transform;
const ctx={setTransform(...v){transform=v;},clearRect(){assert.deepEqual(transform,[1,0,0,1,0,0]);},fillRect(){},drawImage(){},save(){},restore(){},beginPath(){},lineTo(){},moveTo(){},stroke(){}};
const toggles={rectifiedToggle:{checked:false},toggle:{checked:false}};
const env={canvas,ctx,image:{complete:true,naturalWidth:8192,naturalHeight:8686},result:null,rectifiedLayout:null,$:id=>toggles[id],drawDistortionField(){},drawSquarePixels(){},drawRegressionCenters(){}};
vm.createContext(env);vm.runInContext(drawSource,env);
for(let i=0;i<100;i++) env.draw();
assert.equal(assignments,0,'Unchanged zoom redraw must not reallocate canvas');
env.result={image:{width:8192,specimenHeight:8192},rectification:{correctionMatrix:[[1,.02],[0,1]]}};
toggles.rectifiedToggle.checked=true;env.draw();
const afterSwitch=assignments;
for(let i=0;i<100;i++) env.draw();
assert.equal(assignments,afterSwitch,'Rectified zoom redraw must reuse canvas');
toggles.rectifiedToggle.checked=false;env.draw();
assert.deepEqual(transform,[1,0,0,1,0,0],'Switch back must reset rectification transform');
assert.equal(canvas.width,8192);assert.equal(canvas.height,8686);
console.log('Canvas reuse and rectified/original redraw state tests passed');
